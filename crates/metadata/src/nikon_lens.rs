//! The lens a Nikon DSLR used, by name: the Nikon LensID (LensData `0x0098` bytes LensIDNumber … MCUVersion, then
//! LensType `0x0083`) looked up in the table of [`crate::nikon_lens_ids`].
//!
//! LensData from version `0201` on is encrypted with a key made of the body's SerialNumber (`0x001d`) and
//! ShutterCount (`0x00a7`), as the ExifTool tag-name page says. The cipher was written from general knowledge of
//! it, not derived through the clean-room process.
//!
//! Field offsets per LensData version are those of the public ExifTool Nikon tag-name page (LensData00, 01, 0204,
//! 0800). A decoded ID is only trusted when its focal-length bytes agree with the unencrypted Lens record (`0x0084`),
//! so a wrong key (an odd serial number) gives no name rather than another lens's.

use craft_tiff::Ifd;

const SERIAL_NUMBER: u16 = 0x001d;
const LENS_TYPE: u16 = 0x0083;
const SHUTTER_COUNT: u16 = 0x00a7;
const LENS_DATA: u16 = 0x0098;

/// The lens name for a Nikon maker note, when its LensID decodes, checks out against `0x0084` and names one lens.
pub(crate) fn lens_name(note: &Ifd, model: Option<&str>) -> Option<String> {
    let key = lens_id_key(note, model)?;
    let i = crate::nikon_lens_ids::NIKON_LENS_IDS.binary_search_by(|(k, _)| k.cmp(&key)).ok()?;
    let name = crate::nikon_lens_ids::NIKON_LENS_IDS.get(i)?.1;
    // "A or B": the bytes are shared by several lenses; no single name to give
    (!name.contains(" or ") && !name.contains("No CPU")).then(|| name.to_string())
}

/// The 8-byte LensID key, decrypted and checked; `None` for an unknown version or a key that doesn't fit `0x0084`.
pub(crate) fn lens_id_key(note: &Ifd, model: Option<&str>) -> Option<[u8; 8]> {
    let data = note.bytes(LENS_DATA)?;
    let version = data.get(..4)?;
    let (encrypted, at) = match version {
        b"0100" => (false, 6),
        b"0101" => (false, 11),
        b"0201" | b"0202" | b"0203" => (true, 11),
        b"0204" => (true, 12),
        v if v.starts_with(b"08") => (true, 13),
        _ => return None,
    };
    let mut plain = data.get(..at + 7)?.to_vec();
    if encrypted {
        let serial = serial_key(note, model);
        let count = note.value(SHUTTER_COUNT).and_then(|v| v.get_u64(0)).and_then(|c| u32::try_from(c).ok())?;
        decrypt(serial, count, plain.get_mut(4..)?);
    }
    let f = plain.get(at..at + 7)?;
    let lens_type = note.value(LENS_TYPE).and_then(|v| v.get_u64(0)).and_then(|v| u8::try_from(v).ok())?;
    let key = [f[0], f[1], f[2], f[3], f[4], f[5], f[6], lens_type];
    fits_spec(note, f[2], f[3]).then_some(key)
}

/// Whether LensData's focal bytes (`5 · 2^(b/24)` mm) agree with the Lens record's focal range, when there is one.
fn fits_spec(note: &Ifd, min: u8, max: u8) -> bool {
    let Some([short, long, _, _]) = crate::nikon::lens_spec(note) else {
        // no Lens record to check against (a lens reporting nothing): only an all-zero focal range passes
        return min == 0 && max == 0;
    };
    let mm = |b: u8| 5.0 * 2f64.powf(f64::from(b) / 24.0);
    let near = |b: u8, f: f64| (mm(b) / f - 1.0).abs() < 0.06;
    min != 0 && max != 0 && near(min, short) && near(max, long)
}

/// The serial number's part of the key: its value as a decimal number, or a fixed one for a body whose serial
/// number isn't numeric.
fn serial_key(note: &Ifd, model: Option<&str>) -> u8 {
    let serial = note.string(SERIAL_NUMBER).map(|s| s.trim_matches(|c: char| c == '\0' || c.is_whitespace()).to_string());
    match serial.as_deref().filter(|s| !s.is_empty() && s.bytes().all(|b| b.is_ascii_digit())) {
        Some(s) => s.bytes().fold(0u32, |n, b| n.wrapping_mul(10).wrapping_add(u32::from(b - b'0'))) as u8,
        None if model.is_some_and(|m| m.trim().eq_ignore_ascii_case("NIKON D50")) => 0x22,
        None => 0x60,
    }
}

/// Decrypt (or encrypt: the same XOR stream) `data` in place, with the serial number's and shutter count's key.
pub(crate) fn decrypt(serial: u8, count: u32, data: &mut [u8]) {
    let key = count.to_le_bytes().iter().fold(0u8, |k, b| k ^ b);
    let ci = XLAT[0][usize::from(serial)];
    let mut cj = XLAT[1][usize::from(key)];
    let mut ck: u8 = 0x60;
    for b in data {
        cj = cj.wrapping_add(ci.wrapping_mul(ck));
        ck = ck.wrapping_add(1);
        *b ^= cj;
    }
}

