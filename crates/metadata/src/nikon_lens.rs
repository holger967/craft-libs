#[cfg(test)]
mod tests {
    use super::*;
    use craft_tiff::{ByteOrder, IfdBuilder, Tiff, TiffWriter, Value};

    const TAMRON_A14: [u8; 7] = [0x00, 0x3F, 0x2D, 0x80, 0x2C, 0x40, 0x00];
    const TAMRON_A14_NAME: &str = "Tamron AF 18-200mm f/3.5-6.3 XR Di II LD Aspherical (IF) Macro (A14)";

    /// A maker note whose 0204 LensData, encrypted with `serial` and `count`, names `id`; the note itself says
    /// `note_count` for ShutterCount and `spec` for Lens.
    fn note(id: [u8; 7], spec: [f64; 4], serial: &str, count: u32, note_count: u32) -> Ifd {
        let mut data = b"0204".to_vec();
        data.resize(12, 0x11);
        data.extend_from_slice(&id);
        data.resize(33, 0x22);
        let key = serial.parse::<u32>().map(|s| s as u8).unwrap_or(0x60);
        decrypt(key, count, &mut data[4..]);
        let mut b = IfdBuilder::new();
        b.set(SERIAL_NUMBER, Value::Ascii(serial.into()));
        b.set(SHUTTER_COUNT, Value::Long(vec![note_count]));
        b.set(LENS_TYPE, Value::Byte(vec![0x06]));
        b.set(0x0084, Value::Rational(spec.iter().map(|v| ((v * 10.0) as u32, 10)).collect()));
        b.set(LENS_DATA, Value::Undefined(data));
        let bytes = TiffWriter::new(ByteOrder::Little, false).write(&[b]).unwrap();
        Tiff::parse(&bytes).unwrap().ifds.remove(0)
    }

    #[test]
    fn an_encrypted_lens_id_names_the_lens() {
        let n = note(TAMRON_A14, [18.0, 200.0, 3.5, 6.3], "3012345", 51234, 51234);
        assert_eq!(lens_name(&n, Some("NIKON D5000")).as_deref(), Some(TAMRON_A14_NAME));
    }

    #[test]
    fn a_wrong_key_or_a_mismatched_lens_gives_no_name() {
        // read with another shutter count, the bytes decode to noise, which the Lens record refuses
        assert_eq!(lens_name(&note(TAMRON_A14, [18.0, 200.0, 3.5, 6.3], "3012345", 51234, 9), None), None);
        // a decoded 18–200 against a Lens record of 50 mm
        assert_eq!(lens_name(&note(TAMRON_A14, [50.0, 50.0, 1.8, 1.8], "3012345", 51234, 51234), None), None);
    }
}
