"""Nikon LensID table: ExifTool's public tag-name page -> JSON -> Rust.

    python -I scripts/nikon_lens_ids.py extract Nikon.html   # writes crates/metadata/data/nikon_lens_ids.json
    python -I scripts/nikon_lens_ids.py render               # writes crates/metadata/src/nikon_lens_ids.rs

The page is https://exiftool.org/TagNames/Nikon.html ("Nikon LensID Values").
"""
import html, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
JSON = ROOT / "crates/metadata/data/nikon_lens_ids.json"
RS = ROOT / "crates/metadata/src/nikon_lens_ids.rs"


def extract(page):
    text = pathlib.Path(page).read_text(encoding="utf-8")
    start = text.index("name='LensID'>Nikon LensID Values")
    end = text.index("</table>", start)
    rows = re.findall(r"<td>'([0-9A-F ]+?)(?:\.\d+)?'</td><td>= (.*?)</td>", text[start:end])
    table = {}
    for key, name in rows:
        key = key.strip()
        name = html.unescape(re.sub(r"<[^>]*>", "", name)).strip()
        if len(key.split()) != 8 or not name:
            continue
        table.setdefault(key, name)  # a repeated key (ExifTool's ".1"): the first name stands
    out = [[k, table[k]] for k in sorted(table)]
    JSON.write_text(json.dumps(out, ensure_ascii=False, indent=0) + "\n", encoding="utf-8")
    print(f"{len(out)} lens IDs -> {JSON}")


def render():
    rows = json.loads(JSON.read_text(encoding="utf-8"))
    lines = [
        "// @generated by scripts/nikon_lens_ids.py from data/nikon_lens_ids.json; do not edit by hand.",
        "//! Nikon LensID values: the 8 LensData/LensType bytes and the lens they name, sorted by key.",
        "",
        "pub(crate) static NIKON_LENS_IDS: &[([u8; 8], &str)] = &[",
    ]
    for key, name in rows:
        b = ", ".join("0x" + x for x in key.split())
        lines.append(f"    ([{b}], {json.dumps(name, ensure_ascii=False)}),")
    lines.append("];")
    RS.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} lens IDs -> {RS}")


if __name__ == "__main__":
    {"extract": lambda: extract(sys.argv[2]), "render": render}[sys.argv[1]]()
